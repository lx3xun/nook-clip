import AppKit
import CryptoKit
import OSLog

@MainActor
final class ClipboardMonitor {
    nonisolated private static let logger = Logger(subsystem: Bundle.main.bundleIdentifier ?? "com.lx3xun.nookclip", category: "ClipboardMonitor")

    /// 载荷落盘（测试注入替身；默认 FileStore.shared）
    private let payloadStore: any PayloadStore
    private let rustEngine: NookClipHistoryEngine?
    /// 敏感保护开关读取域（测试注入隔离域；默认 standard）
    private let defaults: UserDefaults
    private let excludedAppsManager: ExcludedAppsManager

    init(
        payloadStore: any PayloadStore = FileStore.shared,
        rustEngine: NookClipHistoryEngine? = nil,
        defaults: UserDefaults = .standard,
        excludedAppsManager: ExcludedAppsManager? = nil
    ) {
        self.payloadStore = payloadStore
        self.rustEngine = rustEngine
        self.defaults = defaults
        self.excludedAppsManager = excludedAppsManager ?? .shared
    }
    var onChange: ((ClipboardItem) -> Void)?
    private var timer: Timer?
    /// 捕获处理链（后台串行，保持轮询顺序）
    private var captureChain: Task<Void, Never> = Task {}
    private var lastChangeCount = -1
    private var sourceResolver = SourceAppResolver()
    private var activateObserver: NSObjectProtocol?

    private static let sensitivePasteboardTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType")
    ]

    func start() {
        lastChangeCount = PasteboardAccess.general.changeCount
        let timer = Timer(timeInterval: 0.35, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated {
                self?.poll()
            }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer

        // 记录应用激活历史，供复制来源归因（主线程回调）
        activateObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification,
            object: nil,
            queue: .main
        ) { [weak self] note in
            MainActor.assumeIsolated {
                guard let self,
                      let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication else { return }
                self.sourceResolver.record(
                    bundleId: app.bundleIdentifier,
                    name: app.localizedName ?? app.bundleIdentifier,
                    isSelf: app.processIdentifier == ProcessInfo.processInfo.processIdentifier
                )
            }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        if let activateObserver {
            NSWorkspace.shared.notificationCenter.removeObserver(activateObserver)
            self.activateObserver = nil
        }
    }

    /// 剪贴板轮询检查（定时器与测试主动触发）
    func poll() {
        let pasteboard = PasteboardAccess.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        // 1. 过滤 NookClip 自身写入的粘贴事件
        if pasteboard.types?.contains(PasteService.internalMarker) == true || pasteboard.changeCount == PasteService.lastInternalChangeCount {
            return
        }

        // 1.1 过滤粘贴保护窗口期内相同内容的重入（防止外部应用接管或修改剪切板导致丢失标记）
        if let lastPasted = PasteService.lastPastedSummary,
           let lastTime = PasteService.lastPastedTime,
           Date().timeIntervalSince(lastTime) < 1.5 {
            if let currentText = pasteboard.string(forType: .string), currentText == lastPasted {
                return
            }
        }

        // 2. 来源归因 + 排除应用黑名单（按归因后的来源判定，而非检测时刻的前台应用：
        //    复制后 0.35s 内切走的应用不该顶替真实来源，黑名单应用也不该因切走而漏拦）
        let source = sourceResolver.resolve() ?? Self.frontmostAsSource()
        if let bundleId = source?.bundleId,
           excludedAppsManager.isExcluded(bundleIdentifier: bundleId) {
            return
        }

        // 3. 过滤 1Password/钥匙串等密码管理器敏感数据与临时剪切内容
        if let types = pasteboard.types, types.contains(where: { Self.sensitivePasteboardTypes.contains($0) }) {
            return
        }

        // 4. 主线程一次性快照粘贴板载荷（NSPasteboard 读取留主线程，快），
        //    捕获分析（敏感正则/特征 FFI/哈希/载荷落盘）后台执行
        let snapshot = Self.snapshotPasteboard(
            from: pasteboard,
            sourceBundleId: source?.bundleId,
            sourceAppName: source?.name
        )
        guard snapshot.hasPayload else { return }

        // 5. 捕获链：后台串行处理（保持轮询顺序，前一个未完成时后续排队），
        //    结果回主线程派发 onChange
        let engine = rustEngine ?? AppDependencies.live.rustHistoryStore.engine
        let protectionEnabled = isSensitiveProtectionEnabled
        let lastPastedSummary = PasteService.lastPastedSummary
        let lastPastedTime = PasteService.lastPastedTime?.timeIntervalSince1970
        let payloadStore = self.payloadStore
        let previous = captureChain
        captureChain = Task.detached(priority: .utility) {
            await previous.value

            let isCustomPayloadStore = !(payloadStore is FileStore)
            var rtfDataForIngest = snapshot.rtfData
            if isCustomPayloadStore {
                if let rtf = snapshot.rtfData {
                    if (try? payloadStore.save(data: rtf, preferredExtension: "rtf")) == nil {
                        rtfDataForIngest = nil // 自定义 store 保存 RTF 失败时降级为纯文本
                    }
                }
                if let img = snapshot.imageData {
                    let ext = snapshot.isTIFF ? "tiff" : "png"
                    guard (try? payloadStore.save(data: img, preferredExtension: ext)) != nil else {
                        return // 载荷保存失败拒存该条目
                    }
                }
            }

            let rawSnapshot = RawClipboardSnapshot(
                plainText: snapshot.text,
                html: snapshot.html,
                rtfData: rtfDataForIngest,
                imageData: snapshot.imageData,
                imageExtension: snapshot.imageData != nil ? (snapshot.isTIFF ? "tiff" : "png") : nil,
                filePaths: snapshot.fileURLs.filter { $0.isFileURL }.map(\.path),
                urlCandidates: snapshot.fileURLs.filter { !$0.isFileURL }.map(\.absoluteString),
                urlTitle: snapshot.urlName,
                sourceBundleId: snapshot.sourceBundleId,
                sourceAppName: snapshot.sourceAppName,
                hasConcealedMarker: false
            )
            let assetsDir = payloadStore.directory.path
            let multiTitleTemplate = L10n.tr("item.file_multi_title", "%1$@", 2).replacingOccurrences(of: "2", with: "%2$d")
            let config = IngestConfig(
                sensitiveProtectionEnabled: protectionEnabled,
                excludedBundleIds: [],
                localAssetsDir: assetsDir,
                fileMultiTitleTemplate: multiTitleTemplate,
                defaultImageTitle: L10n.tr("item.type_image")
            )

            let outcome: IngestOutcome
            do {
                outcome = try engine.ingestClipboardSnapshot(
                    snapshot: rawSnapshot,
                    config: config,
                    lastPastedSummary: lastPastedSummary,
                    lastPastedTime: lastPastedTime,
                    nowTs: Date().timeIntervalSince1970
                )
            } catch {
                Self.logger.error("ingestClipboardSnapshot failed: \(error.localizedDescription)")
                return
            }

            // 5.1 粘完即焚：无论是否入库，都要处理「剪贴板里还留着敏感明文」这件事。
            //     验证码会被原地提纯为纯码，敏感内容登记倒计时/粘贴监听；
            //     普通内容则收掉上一次的监听（不常驻监听键盘）。
            //     放在入库之后：历史库里要留原文，剪贴板里只留提纯值。
            let savedItemID: UUID? = {
                if case .saved(let s) = outcome { return UUID(uuidString: s.id) }
                return nil
            }()
            let capturedText = snapshot.text ?? ""
            await MainActor.run {
                AutoBurnController.shared.handleCapturedText(capturedText, itemID: savedItemID)
            }

            guard case .saved(let summary) = outcome else {
                return
            }

            var metadata = ClipboardMetadata()
            if let json = summary.metadataJson, let data = json.data(using: .utf8) {
                metadata = (try? JSONDecoder().decode(ClipboardMetadata.self, from: data)) ?? ClipboardMetadata()
            }

            var item = ClipboardItem(
                id: UUID(uuidString: summary.id) ?? UUID(),
                type: ClipboardItemType(rawValue: summary.itemType) ?? .text,
                title: summary.title,
                summary: summary.summary,
                createdAt: Date(timeIntervalSince1970: summary.createdAt),
                lastUsedAt: Date(timeIntervalSince1970: summary.lastUsedAt),
                copyCount: Int(summary.copyCount),
                isFavorite: summary.favorite,
                payloadPath: summary.payloadPath,
                ocrText: summary.ocrText,
                sourceAppBundleId: summary.sourceAppBundleId,
                sourceAppName: summary.sourceAppName,
                isSensitive: summary.isSensitive,
                sourceDeviceId: summary.sourceDeviceId,
                sourceDeviceName: summary.sourceDeviceName,
                sourcePlatform: summary.sourcePlatform,
                encryptedContent: nil,
                metadata: metadata
            )
            item.decryptedPlainText = nil
            item.persistedKind = summary.kind.isEmpty ? nil : summary.kind
            let finalItem = item
            await MainActor.run { [weak self] in
                self?.onChange?(finalItem)
            }
        }
    }

    /// 粘贴板快照：主线程读取的全部载荷值。捕获分析在后台仅基于快照进行，
    /// 不再触达 NSPasteboard
    private struct PasteboardSnapshot: Sendable {
        var text: String?
        var rtfData: Data?
        var fileURLs: [URL]
        var imageData: Data?
        var isTIFF: Bool
        var urlName: String?
        var html: String?
        var sourceBundleId: String?
        var sourceAppName: String?

        var hasPayload: Bool {
            fileURLs.contains(where: { $0.isFileURL })
                || !(text?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true)
                || imageData != nil
        }
    }

    private static func snapshotPasteboard(
        from pasteboard: NSPasteboard,
        sourceBundleId: String?,
        sourceAppName: String?
    ) -> PasteboardSnapshot {
        let text = pasteboard.string(forType: .string)
        let tiffData = pasteboard.data(forType: .tiff)
        let pngData = tiffData == nil ? pasteboard.data(forType: .png) : nil
        return PasteboardSnapshot(
            text: text,
            rtfData: text != nil ? pasteboard.data(forType: .rtf) : nil,
            fileURLs: ((pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [NSURL])?.compactMap { $0 as URL }) ?? [],
            imageData: tiffData ?? pngData,
            isTIFF: tiffData != nil,
            urlName: pasteboard.string(forType: NSPasteboard.PasteboardType("public.url-name"))?
                .trimmingCharacters(in: .whitespacesAndNewlines),
            html: pasteboard.data(forType: NSPasteboard.PasteboardType("public.html"))
                .flatMap { String(data: $0, encoding: .utf8) },
            sourceBundleId: sourceBundleId,
            sourceAppName: sourceAppName
        )
    }

    /// 敏感保护开关（捕获侧唯一读取点，文件/文本分支共用）。默认开启。
    /// 开启：命中即整条加密入库；关闭：敏感内容不入历史（系统剪贴板原样保留，可直接粘贴）。
    private var isSensitiveProtectionEnabled: Bool {
        defaults.object(forKey: "enableSensitiveProtection") as? Bool ?? true
    }


    /// 无激活记录时的兜底：当前前台应用。前台是 NookClip 自身（刚启动即打开面板）
    /// 时如实标注为 NookClip，而非丢弃来源显示「未知来源」。
    private static func frontmostAsSource() -> SourceAppResolver.Activation? {
        guard let front = NSWorkspace.shared.frontmostApplication else { return nil }
        if front.processIdentifier == ProcessInfo.processInfo.processIdentifier {
            return .init(
                bundleId: Bundle.main.bundleIdentifier,
                name: "NookClip",
                isSelf: false,
                at: Date()
            )
        }
        return .init(
            bundleId: front.bundleIdentifier,
            name: front.localizedName ?? front.bundleIdentifier,
            isSelf: false,
            at: Date()
        )
    }
}
