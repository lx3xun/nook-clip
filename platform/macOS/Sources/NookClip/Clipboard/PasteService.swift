import AppKit

@MainActor
final class PasteService {
    /// 组合根访问点：nonisolated(unsafe) 读该不可变引用安全——实例方法全部
    /// @MainActor 隔离（仍只能在主线程调用），仅允许非隔离静态初始化器
    /// （AppDependencies.live / PreviewDataProvider.live）取引用本身。
    nonisolated static let shared = PasteService()
    nonisolated(unsafe) var defaults: UserDefaults = .standard
    nonisolated(unsafe) var rustEngine: NookClipHistoryEngine?

    /// 非隔离指定初始化器：仅赋默认值（autoClearWorkItem = nil），不触碰
    /// 隔离状态；供 nonisolated(unsafe) shared 初始化使用
    nonisolated init(defaults: UserDefaults = .standard, rustEngine: NookClipHistoryEngine? = nil) {
        self.defaults = defaults
        self.rustEngine = rustEngine
    }
    /// 测试钩子：可替换辅助功能信任态判定与授权弹窗触发，避免测试中弹真实系统框
    nonisolated(unsafe) static var accessibilityTrustChecker: () -> Bool = { AXIsProcessTrusted() }
    nonisolated(unsafe) static var accessibilityPermissionPrompter: () -> Bool = {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        let options = [key: true] as CFDictionary
        return AXIsProcessTrustedWithOptions(options)
    }
    /// 测试钩子：可拦截 ⌘V 模拟按键事件发送
    nonisolated(unsafe) static var postKeyEventHook: (() -> Void)? = nil
    nonisolated static var isAccessibilityTrusted: Bool {
        accessibilityTrustChecker()
    }

    @discardableResult
    static func promptForAccessibilityPermission() -> Bool {
        accessibilityPermissionPrompter()
    }

    /// 若尚未获得辅助功能权限，立即向系统登记并触发 macOS 原生辅助功能授权弹窗。
    /// （单元测试环境下默认跳过真实系统弹窗，测试可通过替换钩子验证调用）
    @discardableResult
    static func promptForAccessibilityPermissionIfNeeded() -> Bool {
        if isAccessibilityTrusted {
            return true
        }
        let isTesting = NSClassFromString("XCTestCase") != nil
        if isTesting && accessibilityTrustCheckerIsDefault {
            return false
        }
        return promptForAccessibilityPermission()
    }

    /// 标记测试是否注入了自定义信任检测钩子
    static var accessibilityTrustCheckerIsDefault = true

    static func openAccessibilitySettings() {
        _ = promptForAccessibilityPermission()
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
            NSWorkspace.shared.open(url)
        }
    }

    /// 真重启：对运行中的自身 bundle 调 NSWorkspace.openApplication 只会激活
    /// 现有实例（AppDelegate 多开守卫还会让新实例直接退出），效果只是退出。
    /// 改为先 spawn 分离的 shell 进程，等旧进程退出后（sleep 1）再以
    /// `open -n` 拉起新实例，最后 terminate 自身。
    /// spawn 失败时仅退出（尽力而为的重启，不阻塞用户发起的重启意图）。
    static func restartApp() {
        let bundlePath = Bundle.main.bundleURL.path
        // 单引号包裹路径防空格；路径内单引号本身按 shell 规则转义
        let escapedPath = "'" + bundlePath.replacingOccurrences(of: "'", with: "'\\''") + "'"
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/bin/sh")
        process.arguments = ["-c", "sleep 1; open -n \(escapedPath)"]
        do {
            try process.run()
        } catch {
            // 尽力而为：拉起脚本失败时退化为仅退出
        }
        DispatchQueue.main.async {
            NSApp.terminate(nil)
        }
    }

    static let internalMarker = NSPasteboard.PasteboardType("com.lx3xun.nookclip.internal-paste")
    private static let transientMarker = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let concealedMarker = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let autoGeneratedMarker = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private(set) static var lastInternalChangeCount: Int = -1
    private(set) static var lastPastedSummary: String? = nil
    private(set) static var lastPastedTime: Date? = nil
    private var autoClearWorkItem: DispatchWorkItem?

    /// 粘贴音效开关（设置 → 通用）：未写入过 UserDefaults 时默认开启
    private static var isPasteSoundEnabled: Bool {
        UserDefaults.standard.object(forKey: "pasteSoundEnabled") == nil
            ? true
            : UserDefaults.standard.bool(forKey: "pasteSoundEnabled")
    }

    /// 粘贴成功时播放短促提示音（复用系统自带音效，不随包分发音频资源）
    private static func playPasteSound() {
        guard isPasteSoundEnabled else { return }
        if let sound = NSSound(named: "Pop") ?? NSSound(named: "Tink") {
            sound.play()
        }
    }

    // MARK: - 文件条目引用校验（原文件被移动/删除或所在卷未挂载时视为失效）

    /// 文件条目引用的原始路径：敏感项解密还原（payloadPath 不落盘明文），
    /// 普通项 payloadPath 优先、缺失时回退 summary 明文。
    /// 多文件复制（Finder 多选）以换行拼接存储：单文件即原始路径，与存量数据同构，无需迁移。
    static func referencedFilePaths(_ item: ClipboardItem) -> [String] {
        guard item.type == .file else { return [] }
        let plain: String
        if item.isSensitive, let decrypted = item.revealPlainContent(), !decrypted.isEmpty {
            plain = decrypted
        } else if let path = item.payloadPath, !path.isEmpty {
            plain = path
        } else if !item.summary.isEmpty {
            plain = item.summary
        } else {
            return []
        }
        return plain.components(separatedBy: "\n").filter { !$0.isEmpty }
    }

    /// 文件条目失效校验：所有引用文件均存在返回 nil，否则返回可直接展示的本地化提示。
    /// 覆盖原文件被移动/删除、外接磁盘或网络卷未挂载等情形。
    func staleFileMessage(for item: ClipboardItem) -> String? {
        guard item.type == .file else { return nil }
        let paths = Self.referencedFilePaths(item)
        guard !paths.isEmpty else {
            return L10n.tr("file.missing.unknown")
        }
        let missing = paths.filter { !FileManager.default.fileExists(atPath: $0) }
        guard !missing.isEmpty else { return nil }
        return L10n.tr("file.missing.message", missing.joined(separator: "\n"))
    }

    @discardableResult
    func copyOnly(_ item: ClipboardItem, plainTextOnly: Bool = false) -> Bool {
        let engine = rustEngine ?? AppDependencies.live.rustHistoryStore.engine
        do {
            let payload = try engine.preparePastePayload(id: item.id.uuidString, plainTextOnly: plainTextOnly)
            return writePreparedPayload(payload, fallbackSummary: item.summary, plainTextOnly: plainTextOnly)
        } catch let error as NookClipError {
            switch error {
            case .NotFound:
                break
            case .StaleFiles, .CorruptedImagePayload, .DecryptionFailed:
                return false
            default:
                break
            }
        } catch {}

        // 内存中尚未持久化或测试临时构造的条目（兜底执行原生系统剪贴板写入与校验）
        if item.isSensitive {
            guard case .success = item.revealPlainContentResult() else {
                return false
            }
        }
        if item.type == .file {
            let paths = Self.referencedFilePaths(item)
            guard !paths.isEmpty, paths.allSatisfy({ FileManager.default.fileExists(atPath: $0) }) else {
                return false
            }
        } else if item.type == .image {
            guard let path = item.payloadPath, FileStore.shared.load(path: path) != nil else {
                return false
            }
        }
        let plainText = item.isSensitive ? (item.revealPlainContent() ?? item.summary) : item.summary
        let pasteboard = PasteboardAccess.general
        pasteboard.clearContents()
        let success: Bool

        switch item.type {
        case .text, .url:
            success = pasteboard.setString(plainText, forType: .string)
            if !item.isSensitive && !plainTextOnly, let path = item.payloadPath, path.lowercased().hasSuffix(".rtf"),
               let data = FileStore.shared.load(path: path) {
                pasteboard.setData(data, forType: .rtf)
            }
        case .file:
            let filePaths = Self.referencedFilePaths(item)
            let joinedPath = item.isSensitive ? plainText : filePaths.joined(separator: "\n")
            if plainTextOnly {
                success = pasteboard.setString(joinedPath, forType: .string)
            } else {
                let urls = filePaths.map { URL(fileURLWithPath: $0) as NSURL }
                let writeObjSuccess = pasteboard.writeObjects(urls)
                pasteboard.setString(joinedPath, forType: .string)
                if let singlePath = filePaths.first,
                   filePaths.count == 1,
                   ClipboardRowModel.isSingleImageFilePath(singlePath),
                   let fileData = try? Data(contentsOf: URL(fileURLWithPath: singlePath)) {
                    let ext = (singlePath as NSString).pathExtension.lowercased()
                    if ext == "png" {
                        pasteboard.setData(fileData, forType: .png)
                    } else if ext == "tiff" || ext == "tif" {
                        pasteboard.setData(fileData, forType: .tiff)
                    }
                    if let image = NSImage(contentsOfFile: singlePath),
                       let tiff = image.tiffRepresentation {
                        pasteboard.setData(tiff, forType: .tiff)
                    }
                }
                success = writeObjSuccess
            }
        case .image:
            if let path = item.payloadPath, let data = FileStore.shared.load(path: path) {
                let type: NSPasteboard.PasteboardType = path.lowercased().hasSuffix(".png") ? .png : .tiff
                success = pasteboard.setData(data, forType: type)
            } else {
                success = false
            }
        }

        if success {
            finalizeClipboardWrite(
                pasteboard: pasteboard,
                containsSensitive: item.isSensitive,
                plainText: plainText
            )
        }
        return success
    }

    private func writePreparedPayload(_ payload: PreparedPastePayload, fallbackSummary: String, plainTextOnly: Bool) -> Bool {
        switch payload.itemType {
        case "text", "url", "file":
            guard payload.plainText != nil else { return false }
        case "image":
            guard payload.imageData != nil else { return false }
        default:
            return false
        }

        let pasteboard = PasteboardAccess.general
        pasteboard.clearContents()
        let success: Bool
        switch payload.itemType {
        case "text", "url":
            guard let text = payload.plainText else { return false }
            let writeSuccess = pasteboard.setString(text, forType: .string)
            if let rtf = payload.rtfData, !plainTextOnly {
                pasteboard.setData(rtf, forType: .rtf)
            }
            success = writeSuccess
        case "file":
            guard let joinedPath = payload.plainText else { return false }
            if plainTextOnly {
                success = pasteboard.setString(joinedPath, forType: .string)
            } else {
                let urls = payload.filePaths.map { URL(fileURLWithPath: $0) as NSURL }
                let writeObjSuccess = pasteboard.writeObjects(urls)
                pasteboard.setString(joinedPath, forType: .string)
                if payload.isSingleImageFile, let singlePath = payload.filePaths.first,
                   let fileData = try? Data(contentsOf: URL(fileURLWithPath: singlePath)) {
                    let ext = (singlePath as NSString).pathExtension.lowercased()
                    if ext == "png" {
                        pasteboard.setData(fileData, forType: .png)
                    } else if ext == "tiff" || ext == "tif" {
                        pasteboard.setData(fileData, forType: .tiff)
                    }
                    if let image = NSImage(contentsOfFile: singlePath),
                       let tiff = image.tiffRepresentation {
                        pasteboard.setData(tiff, forType: .tiff)
                    }
                }
                success = writeObjSuccess
            }
        case "image":
            guard let data = payload.imageData else { return false }
            let type: NSPasteboard.PasteboardType = payload.imageFormat == "png" ? .png : .tiff
            success = pasteboard.setData(data, forType: type)
        default:
            success = false
        }

        if success {
            finalizeClipboardWrite(
                pasteboard: pasteboard,
                containsSensitive: payload.isSensitive,
                plainText: payload.plainText ?? fallbackSummary
            )
        }
        return success
    }
    func copyText(_ text: String, containsSensitive: Bool = false) -> Bool {
        let pasteboard = PasteboardAccess.general
        pasteboard.clearContents()
        let success = pasteboard.setString(text, forType: .string)
        if success {
            finalizeClipboardWrite(pasteboard: pasteboard, containsSensitive: containsSensitive, plainText: text)
        }
        return success
    }

    /// 写入成功后的统一收尾（T023 纯去重，行为不变）：internal 标记、
    /// 敏感标记 + 自毁调度（或取消既有调度）、粘贴状态记录。
    private func finalizeClipboardWrite(pasteboard: NSPasteboard, containsSensitive: Bool, plainText: String) {
        pasteboard.setData(Data(), forType: Self.internalMarker)
        if containsSensitive {
            pasteboard.setData(Data(), forType: Self.transientMarker)
            pasteboard.setData(Data(), forType: Self.concealedMarker)
            pasteboard.setData(Data(), forType: Self.autoGeneratedMarker)
            scheduleSensitiveClipboardClear(expectedChangeCount: pasteboard.changeCount, plainText: plainText)
        } else {
            cancelAutoClearTimer()
        }
        Self.lastInternalChangeCount = pasteboard.changeCount
        Self.lastPastedSummary = plainText
        Self.lastPastedTime = Date()
    }


    func paste(_ item: ClipboardItem, targetApplication: NSRunningApplication? = nil, plainTextOnly: Bool = false) -> Bool {
        // 1. 先确保内容成功写入系统剪切板
        guard copyOnly(item, plainTextOnly: plainTextOnly) else { return false }

        // 2. 检查辅助功能权限；若无权限，已写入剪切板，向系统触发授权引导弹窗并返回 false
        guard Self.isAccessibilityTrusted else {
            Self.promptForAccessibilityPermissionIfNeeded()
            return false
        }

        // 3. 激活目标应用并等待焦点就绪后模拟 ⌘V 击键
        let target = (targetApplication != nil && targetApplication?.bundleIdentifier != Bundle.main.bundleIdentifier)
            ? targetApplication
            : nil
        activateAndPostKeyEvent(target: target)
        return true
    }

    /// 合并粘贴入口（specs/001 US5）：文本已由调用方按序合并，此处复制 + 模拟 ⌘V。
    /// UI 层禁止直调 CGEvent，统一经此方法（contracts C2）。
    /// - Parameter containsSensitive: 合并文本是否含敏感明文，透传给 copyText
    ///   （批量粘贴的敏感保护，审计 BUG-052）
    @discardableResult
    func pasteText(_ text: String, targetApplication: NSRunningApplication? = nil, containsSensitive: Bool = false) -> Bool {
        guard copyText(text, containsSensitive: containsSensitive) else { return false }
        guard Self.isAccessibilityTrusted else {
            Self.promptForAccessibilityPermissionIfNeeded()
            return false
        }

        let target = (targetApplication != nil && targetApplication?.bundleIdentifier != Bundle.main.bundleIdentifier)
            ? targetApplication
            : nil
        activateAndPostKeyEvent(target: target)
        return true
    }

    /// 激活目标应用并在焦点就绪后模拟 ⌘V 击键（T023 纯去重，paste/pasteText 共用）。
    private func activateAndPostKeyEvent(target: NSRunningApplication?) {
        target?.activate()

        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            Self.postPasteKeyEvent()
        }
        Self.playPasteSound()
    }

    private static func postPasteKeyEvent() {
        if let hook = postKeyEventHook {
            hook()
            return
        }
        let source = CGEventSource(stateID: .combinedSessionState)
        // 虚拟键码 0x09 为按键 'v'
        guard let keyDown = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: false) else {
            return
        }
        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand

        // 仅通过 session tap 派发单一按键事件，避免双重派发导致重复粘贴
        keyDown.post(tap: .cgAnnotatedSessionEventTap)
        keyUp.post(tap: .cgAnnotatedSessionEventTap)
    }

    // MARK: - 敏感数据剪切板自动自毁清理

    private func scheduleSensitiveClipboardClear(expectedChangeCount: Int, plainText: String) {
        cancelAutoClearTimer()
        
        let timeoutSeconds: Int
        if defaults.object(forKey: "sensitiveClipboardTimeout") == nil {
            timeoutSeconds = 30
        } else {
            timeoutSeconds = defaults.integer(forKey: "sensitiveClipboardTimeout")
        }
        guard timeoutSeconds > 0 else { return }
        
        let workItem = DispatchWorkItem {
            let pb = PasteboardAccess.general
            // 仅当剪切板尚未被用户后续其他复制覆盖时清理
            if pb.changeCount == expectedChangeCount || pb.string(forType: .string) == plainText {
                pb.clearContents()
                Self.lastInternalChangeCount = pb.changeCount
            }
            // 顺带清掉内存中的敏感明文摘要（审查 C2）：重入窗口过后不再保留
            Self.lastPastedSummary = nil
        }
        self.autoClearWorkItem = workItem
        DispatchQueue.main.asyncAfter(deadline: .now() + Double(timeoutSeconds), execute: workItem)
    }

    private func cancelAutoClearTimer() {
        autoClearWorkItem?.cancel()
        autoClearWorkItem = nil
    }

    /// 敏感明文查看到期后的自毁入口（specs/001 US3）：仅当系统剪贴板仍为该明文时清空。
    /// UI 层禁止直调 NSPasteboard（宪法 II），必须经此方法。
    func clearClipboardIfContent(matches plainText: String) {
        let pb = PasteboardAccess.general
        if pb.string(forType: .string) == plainText {
            pb.clearContents()
            Self.lastInternalChangeCount = pb.changeCount
        }
    }
}
