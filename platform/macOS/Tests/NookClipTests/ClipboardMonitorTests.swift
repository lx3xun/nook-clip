import XCTest
@testable import NookClip

@MainActor
final class ClipboardMonitorTests: XCTestCase {

    func testMonitorFiltersSelfInternalPasteMarker() async throws {
        let defaults = makeIsolatedDefaults()
        let monitor = ClipboardMonitor(defaults: defaults)
        var captured: ClipboardItem?
        monitor.onChange = { captured = $0 }

        try await withPasteboardLock {
            let pb = PasteboardAccess.general
            pb.clearContents()
            pb.declareTypes([.string, PasteService.internalMarker], owner: nil)
            pb.setString("NookClip Internal Copy", forType: .string)
            pb.setData(Data(), forType: PasteService.internalMarker)

            monitor.poll()
            try await Task.sleep(nanoseconds: 50_000_000)
        }

        XCTAssertNil(captured, "带有 internalMarker 的自身粘贴事件必须被过滤，不能捕获")
    }

    func testMonitorFiltersProtectedReentryWindow() async throws {
        let defaults = makeIsolatedDefaults()
        let monitor = ClipboardMonitor(defaults: defaults)
        var captured: ClipboardItem?
        monitor.onChange = { captured = $0 }

        try await withPasteboardLock {
            let secret = "PastedSummary-\(UUID().uuidString)"
            PasteService.shared.copyText(secret)

            let pb = PasteboardAccess.general
            // 外部无 internalMarker 模拟重入，但内容在 1.5s 保护期内且与 lastPastedSummary 相同
            pb.clearContents()
            pb.setString(secret, forType: .string)

            monitor.poll()
            try await Task.sleep(nanoseconds: 50_000_000)
        }

        XCTAssertNil(captured, "在 1.5s 窗口期内重入的相同内容必须被过滤")
    }

    func testMonitorFiltersExcludedApps() async throws {
        let defaults = makeIsolatedDefaults()
        let excludedManager = ExcludedAppsManager(defaults: defaults)
        excludedManager.add(bundleIdentifier: "com.test.excludedApp", name: "Excluded Test App")

        let monitor = ClipboardMonitor(defaults: defaults, excludedAppsManager: excludedManager)
        var captured: ClipboardItem?
        monitor.onChange = { captured = $0 }

        // 模拟外部被排除的应用激活
        let notification = Notification(
            name: NSWorkspace.didActivateApplicationNotification,
            object: nil,
            userInfo: [
                NSWorkspace.applicationUserInfoKey: MockRunningApp(
                    bundleIdentifier: "com.test.excludedApp",
                    localizedName: "Excluded Test App",
                    processIdentifier: 99999
                )
            ]
        )
        // 注册观察者
        monitor.start()
        defer { monitor.stop() }
        NSWorkspace.shared.notificationCenter.post(notification)

        try await withPasteboardLock {
            let pb = PasteboardAccess.general
            pb.clearContents()
            pb.setString("Content from excluded app", forType: .string)

            monitor.poll()
            try await Task.sleep(nanoseconds: 80_000_000)
        }

        XCTAssertNil(captured, "归因为已排除应用的剪贴板内容必须被跳过")
    }

    func testMonitorFiltersPasswordManagerTransientTypes() async throws {
        let types: [NSPasteboard.PasteboardType] = [
            .init("org.nspasteboard.TransientType"),
            .init("org.nspasteboard.ConcealedType"),
            .init("org.nspasteboard.AutoGeneratedType"),
            .init("com.agilebits.onepassword"),
            .init("de.petermaurer.TransientPasteboardType")
        ]

        for sensitiveType in types {
            let defaults = makeIsolatedDefaults()
            let monitor = ClipboardMonitor(defaults: defaults)
            var captured: ClipboardItem?
            monitor.onChange = { captured = $0 }

            try await withPasteboardLock {
                let pb = PasteboardAccess.general
                pb.clearContents()
                pb.declareTypes([.string, sensitiveType], owner: nil)
                pb.setString("Password-\(UUID().uuidString)", forType: .string)
                pb.setData(Data(), forType: sensitiveType)

                monitor.poll()
                try await Task.sleep(nanoseconds: 50_000_000)
            }

            XCTAssertNil(captured, "类型包含 \(sensitiveType.rawValue) 时必须被过滤")
        }
    }

    func testMonitorCapturesValidPlainText() async throws {
        let defaults = makeIsolatedDefaults()
        let monitor = ClipboardMonitor(defaults: defaults)
        var captured: ClipboardItem?
        monitor.onChange = { captured = $0 }

        let text = "Valid Plain Text \(UUID().uuidString)"
        try await withPasteboardLock {
            let pb = PasteboardAccess.general
            pb.clearContents()
            pb.setString(text, forType: .string)

            monitor.poll()
            // 等待捕获链后台处理完成派发
            let start = Date()
            while captured == nil && Date().timeIntervalSince(start) < 1.0 {
                try await Task.sleep(nanoseconds: 20_000_000)
            }
        }

        XCTAssertNotNil(captured, "有效纯文本应当被成功捕获")
        XCTAssertEqual(captured?.summary, text)
    }
}

private final class MockRunningApp: NSRunningApplication, @unchecked Sendable {
    private let _bundleIdentifier: String?
    private let _localizedName: String?
    private let _processIdentifier: pid_t

    init(bundleIdentifier: String?, localizedName: String?, processIdentifier: pid_t) {
        self._bundleIdentifier = bundleIdentifier
        self._localizedName = localizedName
        self._processIdentifier = processIdentifier
        super.init()
    }

    override var bundleIdentifier: String? { _bundleIdentifier }
    override var localizedName: String? { _localizedName }
    override var processIdentifier: pid_t { _processIdentifier }
}
